// -*- verilog -*-
// addr_gen.v — 곱셈기 없이 "r*301+d" 룩업테이블 주소를 만든다.
//
// table_width=301은 2의 거듭제곱이 아니라 그냥 시프트로 곱셈을 대신할 수 없다.
// 하지만 "상수" 곱셈(301처럼 고정된 값)은 그 상수를 2의 거듭제곱의 합으로
// 쪼개서, 시프트(공짜, 배선만 바뀜) + 덧셈 몇 번으로 풀 수 있다:
//
//   301 = 256 + 32 + 8 + 4 + 1 = 2^8 + 2^5 + 2^3 + 2^2 + 2^0
//   r*301 = (r<<8) + (r<<5) + (r<<3) + (r<<2) + r
//
// 진짜 곱셈기(N비트 x N비트, 부분곱 N개를 다 더해야 함) 대신 덧셈 4번으로
// 끝난다 — sensor_pe.v를 만들 때와 같은 철학(대량 병렬화할 걸 대비해 비싼
// 연산을 최대한 싼 것으로 바꿔둔다).

module addr_gen #(
    parameter RD_W   = 9,    // r, d 각각 0~300, 9비트면 충분(2^9=512)
    parameter ADDR_W = 17    // 301*301-1=90600 < 2^17
) (
    input  wire [RD_W-1:0]   r,   // 관측거리 (표의 행)
    input  wire [RD_W-1:0]   d,   // 기대거리 (표의 열)
    output wire [ADDR_W-1:0] addr
);

    wire [ADDR_W-1:0] r_ext = r;  // 9비트 -> 17비트 zero-extend

    // r*301 = (r<<8)+(r<<5)+(r<<3)+(r<<2)+r  (301 = 256+32+8+4+1)
    wire [ADDR_W-1:0] r_x301 = (r_ext << 8) + (r_ext << 5) + (r_ext << 3)
                              + (r_ext << 2) + r_ext;

    assign addr = r_x301 + d;

endmodule
